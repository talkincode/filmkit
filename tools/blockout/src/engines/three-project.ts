// The Three.js / HyperFrames engine's SOURCE project: plain files, no network, no
// build step. `hyperframes check` and `hyperframes render` (and so filmkit's existing
// hyperframes Profile) work on it as they do on any HyperFrames project.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fail, io } from "../errors.ts";
import { sha256Bytes } from "../hash.ts";
import { HYPERFRAMES_PIN, TOOL_VERSION } from "../version.ts";
import type { LoadedScene } from "../scene.ts";

const RUNTIME = join(import.meta.dir, "..", "..", "runtime");
const VENDOR = join(import.meta.dir, "..", "..", "vendor", "three");

export interface Vendor {
  version: string;
  files: Record<string, string>;
}

/** The vendored library, verified against its pin; a modified copy is refused. */
export function readVendor(): { pins: Vendor; files: Record<string, Uint8Array> } {
  const meta = JSON.parse(readFileSync(join(VENDOR, "VENDOR.json"), "utf8")) as { version: string; sha256: Record<string, string> };
  const files: Record<string, Uint8Array> = {};
  for (const [name, expected] of Object.entries(meta.sha256)) {
    const bytes = readFileSync(join(VENDOR, name));
    const actual = sha256Bytes(bytes);
    if (actual !== expected) {
      return fail(io(`vendored ${name} does not match its pinned sha256`, { hint: `expected ${expected}, found ${actual}; restore tools/blockout/vendor/three from git` }));
    }
    files[name] = bytes;
  }
  return { pins: { version: meta.version, files: meta.sha256 }, files };
}

export interface ProjectFile {
  /** Relative to the project directory. */
  path: string;
  data: Uint8Array;
}

const enc = (s: string) => new TextEncoder().encode(s);
/** JS number -> attribute text that parses back to the same number. */
const num = (n: number) => String(n);

function composition(loaded: LoadedScene, mode: "video" | "overview"): string {
  const { width, height } = loaded.compiled;
  const { fps, durationFrames } = loaded.scene.timing;
  // overview is one still: a one-frame composition at the same fps
  const frames = mode === "overview" ? 1 : durationFrames;
  // the overview lives in compositions/ (HyperFrames lints a second root-level composition as an error)
  const base = mode === "overview" ? ".." : ".";
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${width}, height=${height}" />
    <title>blockout ${loaded.scene.id}${mode === "overview" ? " (overview)" : ""}</title>
    <style>
      html, body { margin: 0; background: ${loaded.compiled.background}; }
      #root { position: relative; width: 100%; height: 100%; overflow: hidden; }
      #stage { position: absolute; inset: 0; width: 100%; height: 100%; display: block; }
    </style>
  </head>
  <body>
    <!-- No GSAP timeline on purpose: the scene is a pure function of time, applied on every hf-seek. -->
    <div id="root" data-composition-id="blockout" data-no-timeline data-start="0" data-width="${width}" data-height="${height}" data-fps="${fps}" data-duration="${num(frames / fps)}">
      <canvas id="stage" width="${width}" height="${height}" data-layout-allow-overflow></canvas>
    </div>
    <script type="module">
      import { mountBlockout } from "${base}/blockout-three.js";
      import data from "${base}/scene-data.js";
      mountBlockout({ canvas: document.getElementById("stage"), data, mode: "${mode}" });
    </script>
  </body>
</html>
`;
}

/** Every file of the Three.js project, in memory. Deterministic: same declaration, same bytes. */
export function threeProjectFiles(loaded: LoadedScene): { files: ProjectFile[]; vendor: Vendor } {
  const vendor = readVendor();
  const read = (name: string) => new Uint8Array(readFileSync(join(RUNTIME, name)));
  const files: ProjectFile[] = [
    { path: "index.html", data: enc(composition(loaded, "video")) },
    { path: "compositions/overview.html", data: enc(composition(loaded, "overview")) },
    { path: "blockout-core.js", data: read("blockout-core.js") },
    { path: "blockout-three.js", data: read("blockout-three.js") },
    { path: "scene-data.js", data: enc(`export default ${JSON.stringify(loaded.scene)};\n`) },
    ...Object.entries(vendor.files).map(([name, data]) => ({ path: name === "LICENSE" ? "vendor/LICENSE-three" : `vendor/${name}`, data })),
    {
      path: "package.json",
      data: enc(
        `${JSON.stringify(
          {
            name: `blockout-${loaded.scene.id}`,
            private: true,
            version: "1.0.0",
            description: `Generated by blockout ${TOOL_VERSION}. Open index.html with HyperFrames; nothing here is fetched at render time.`,
            scripts: { check: "hyperframes check", render: "hyperframes render --output reference.mp4" },
            dependencies: { hyperframes: HYPERFRAMES_PIN },
          },
          null,
          2,
        )}\n`,
      ),
    },
  ];
  return { files, vendor: vendor.pins };
}

export function writeProject(dir: string, files: ProjectFile[]): void {
  for (const f of files) {
    const target = join(dir, f.path);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, f.data);
  }
}
