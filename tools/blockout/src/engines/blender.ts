// Blender engine. blockout evaluates the scene (shared evaluator -> bake.json); the
// Python inside Blender (runtime/blender/*.py) only builds and keys what the bake
// lists. Rendering is plain Blender CLI: `blender -b scene.blend -a`.

import { copyFileSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fail, toolFailure } from "../errors.ts";
import { run, runOk, tail } from "../exec.ts";
import { checkFrames, pixelHash } from "../media.ts";
import { findBlender, type Blender } from "../tools.ts";
import type { LoadedScene } from "../scene.ts";
import { bake } from "./bake.ts";
import { SEEK_SKIPPED, seekFrames, type EngineRender } from "./types.ts";

const SCRIPTS = join(import.meta.dir, "..", "..", "runtime", "blender");
const SCRIPT_FILES = ["build_scene.py", "render_overview.py", "verify_seek.py", "validate_scene.py"];

export interface BlenderOptions {
  blender?: string;
  seekSamples: number;
}

const blenderArgs = (b: Blender, ...rest: string[]) => [b.path, "-b", "--factory-startup", "--python-exit-code", "7", ...rest];

/** bake.json + scripts + scene.blend in `projectDir`. Needs Blender (to write the native file). */
export async function writeBlenderProject(loaded: LoadedScene, projectDir: string, b: Blender) {
  mkdirSync(projectDir, { recursive: true });
  const data = bake(loaded);
  writeFileSync(join(projectDir, "bake.json"), JSON.stringify(data));
  for (const f of SCRIPT_FILES) copyFileSync(join(SCRIPTS, f), join(projectDir, f));
  writeFileSync(
    join(projectDir, "README.txt"),
    [
      "Blender project generated by blockout.",
      "  scene.blend      the native project (Workbench render, 1 Blender unit = 1 meter, Z up)",
      "  bake.json        what the shared evaluator computed for every frame (meshes, poses, camera)",
      "  build_scene.py   rebuilds scene.blend from bake.json:",
      "                   blender -b --factory-startup -P build_scene.py -- bake.json scene.blend",
      "Render the video frames:  blender -b scene.blend -o //render/f_#### -a",
      "Render the overview:      blender -b scene.blend -P render_overview.py -- overview.png",
      "",
    ].join("\n"),
  );
  const build = await runOk(blenderArgs(b, "-P", join(projectDir, "build_scene.py"), "--", join(projectDir, "bake.json"), join(projectDir, "scene.blend")), "Blender build_scene.py", { cwd: projectDir });
  if (!build.stdout.includes("BLOCKOUT-BUILT")) return fail(toolFailure("Blender ran build_scene.py but did not report a built scene", { hint: tail(build.stdout) }));
  return data;
}

export async function renderBlender(loaded: LoadedScene, stage: string, opts: BlenderOptions): Promise<EngineRender> {
  const { durationFrames } = loaded.scene.timing;
  const { width, height } = loaded.compiled;
  const b = await findBlender(opts.blender);
  const projectDir = join(stage, "source", "blender");
  const work = join(stage, "work", "blender");
  const seqDir = join(work, "frames");
  mkdirSync(seqDir, { recursive: true });
  await writeBlenderProject(loaded, projectDir, b);
  const blend = join(projectDir, "scene.blend");

  await runOk(blenderArgs(b, blend, "-o", join(seqDir, "f_####"), "-a"), "Blender render (blender -b scene.blend -a)", { cwd: projectDir, timeout: 30 * 60_000 });
  const names = readdirSync(seqDir).filter((n) => /^f_\d{4}\.png$/.test(n));
  if (names.length !== durationFrames) {
    return fail(toolFailure(`Blender rendered ${names.length} frames, the scene declares ${durationFrames}`));
  }
  const framePath = (f: number) => join(seqDir, `f_${String(f).padStart(4, "0")}.png`);
  checkFrames(framePath, durationFrames, width, height, "Blender render");

  const overviewPath = join(work, "overview.png");
  await runOk(blenderArgs(b, blend, "-P", join(projectDir, "render_overview.py"), "--", overviewPath), "Blender overview render", { cwd: projectDir });
  checkFrames(() => overviewPath, 1, width, height, "Blender overview render");

  // random access: jump to frames out of order, compare poses with the evaluator, render, compare pixels
  const visit = seekFrames(loaded.sha256, durationFrames, opts.seekSamples);
  let identical = true;
  let stateMaxError = 0;
  if (visit.length) {
    const seekDir = join(work, "seek");
    const r = await run(blenderArgs(b, blend, "-P", join(projectDir, "verify_seek.py"), "--", join(projectDir, "bake.json"), seekDir, visit.join(",")), { cwd: projectDir, timeout: 15 * 60_000 });
    if (r.status !== 0) {
      return fail(toolFailure("Blender's pose at a random frame differs from the evaluator's", { hint: tail(`${r.stdout}\n${r.stderr}`) }));
    }
    stateMaxError = Number(/worst=(\S+)/.exec(r.stdout)?.[1] ?? NaN);
    if (!Number.isFinite(stateMaxError)) return fail(toolFailure("Blender did not report a finite seek state error"));
    for (const f of visit) {
      const shot = join(seekDir, `seek_${String(f).padStart(4, "0")}.png`);
      if ((await pixelHash(shot)) !== (await pixelHash(framePath(f)))) {
        identical = false;
        break;
      }
    }
  }
  if (!identical) return fail(toolFailure("rendering a frame out of order gave different pixels than the sequential render"));

  return {
    name: "blender",
    version: b.version,
    renderer: "BLENDER_WORKBENCH",
    pins: { blender: b.label },
    framePath,
    sequence: { pattern: join(seqDir, "f_%04d.png"), startNumber: 0 },
    overviewPath,
    seek:
      visit.length === 0
        ? SEEK_SKIPPED
        : {
            status: "verified",
            frames: visit,
            identical,
            stateMaxError,
            method: "blender -b scene.blend: frame_set() to each frame out of order; object world poses vs the evaluator, then decoded-pixel sha256 of the render vs the sequential frame",
          },
  };
}

/** Blender validating its own native project: the .blend opens and contains exactly what was baked. */
export async function validateBlenderProject(loaded: LoadedScene, dir: string, blenderPath?: string): Promise<{ blender: string; objects: number }> {
  const b = await findBlender(blenderPath);
  await writeBlenderProject(loaded, dir, b);
  const r = await run(blenderArgs(b, join(dir, "scene.blend"), "-P", join(dir, "validate_scene.py"), "--", join(dir, "bake.json")), { cwd: dir, timeout: 5 * 60_000 });
  const line = /BLOCKOUT-VALIDATE (\{.*\})/.exec(r.stdout)?.[1];
  if (!line) return fail(toolFailure("Blender did not report a validation result", { hint: tail(`${r.stdout}\n${r.stderr}`) }));
  const result = JSON.parse(line) as { ok: boolean; errors: string[]; objects: number; blender: string };
  if (!result.ok || r.status !== 0) return fail(...result.errors.map((e) => toolFailure(`Blender native validation: ${e}`)));
  return { blender: result.blender, objects: result.objects };
}
